    private void autoGenerateDescriptionFromTitle() {
        if (addEventTitre == null || addEventDescr == null) {
            return;
        }
        String title = addEventTitre.getText() != null ? addEventTitre.getText().trim() : "";
        String currentDesc = addEventDescr.getText() != null ? addEventDescr.getText().trim() : "";
        if (title.isBlank()) {
            return;
        }
        if (!currentDesc.isBlank()) {
            return;
        }
        if (title.equalsIgnoreCase(lastGeneratedTitle)) {
            return;
        }

        addEventDescr.setPromptText("Generation automatique via Cohere...");
        javafx.concurrent.Task<String> task = new javafx.concurrent.Task<>() {
            @Override
            protected String call() throws Exception {
                return cohereEventDescriptionService.generateDescriptionFromTitle(title);
            }
        };
        task.setOnSucceeded(ev -> {
            String generated = task.getValue();
            if (generated != null && !generated.isBlank()) {
                String safe = generated.length() > MAX_EVENT_DESCRIPTION
                        ? generated.substring(0, MAX_EVENT_DESCRIPTION).trim()
                        : generated;
                addEventDescr.setText(safe);
                lastGeneratedTitle = title;
            }
            addEventDescr.setPromptText("Choisissez un titre");
        });
        task.setOnFailed(ev -> {
            addEventDescr.setText("Description automatique temporairement indisponible. Veuillez saisir une description manuellement.");
            addEventDescr.setPromptText("Choisissez un titre");
        });

        Thread worker = new Thread(task, "cohere-event-description");
        worker.setDaemon(true);
        worker.start();
    }
